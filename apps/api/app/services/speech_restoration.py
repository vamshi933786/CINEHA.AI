logger = logging.getLogger(__name__)


class SpeechRestorationResult(BaseModel):
    """Normalized result returned by speech restoration providers."""
    segments: List[TranscriptSegment]
    full_text: str
    is_restored: bool
    provider_name: str
    notice: Optional[str] = None
    metadata: Dict[str, Any] = Field(default_factory=dict)


class SpeechRestorationValidationError(Exception):
    """Raised when restoration output violates the strict 1:1 segment contract."""
    pass


class BaseSpeechRestorationProvider(ABC):
    """Abstract interface for speech restoration providers."""

    @abstractmethod
    async def restore_telugu_speech(
        self,
        segments: List[TranscriptSegment],
        context: Optional[str] = None,
    ) -> SpeechRestorationResult:
        """
        Restore phonetically noisy Telugu speech segments into clean, natural Telugu text.
        Guarantees exact preservation of segment count, order, and start/end timestamps.
        """
        pass


SYSTEM_RESTORATION_PROMPT = """You are CINEHA AI's expert speech restoration engine specializing in Telugu and Tanglish short-form video captions.
You receive raw phonetic speech-to-text segments generated by an on-device Whisper model listening to a Telugu content creator.
Because Whisper's Telugu training is limited, the phonetic transcript has corrupted spellings and misrecognized English creator terminology, but the acoustic segment boundaries are accurate.

CRITICAL MISSION:
Reconstruct the true spoken Telugu speech supported by the phonetic Whisper tokens.
This is speech restoration, NOT creative writing.

STRICT ANTI-HALLUCINATION RULES:
1. Reconstruct ONLY what is reasonably supported by the supplied Whisper phonetic transcript.
2. NEVER invent facts, add explanations, rewrite the speaker's meaning, add missing sentences, or create plausible dialogue.
3. STRICT 1-TO-1 SEGMENT MAPPING: Return exactly one restored segment per input segment with the identical segment ID.
4. PRESERVE SEGMENT ORDER: Do NOT reorder, merge, split, or omit segments.
5. NO TIMESTAMPS: Do NOT generate, output, or modify timestamps. Timestamps belong exclusively to the audio model.
6. PRESERVE CREATOR TERMINOLOGY & ENGLISH CODE-SWITCHING: Creators mix Telugu with English film jargon. Preserve meaningful terms such as:
   composition, framing, shoot, lighting, video, cinematic, content creator, episode, subject, object, background, camera, angle, cut.
7. UNINTELLIGIBLE SPEECH / NOISE HANDLING:
   - If speech is genuinely unclear or unintelligible: output '[అర్థం కాలేదు]' rather than inventing content.
   - For obvious background noise or microphone hiss: output '[శబ్దం]'.
   - For unintelligible content or random corrupted artifacts: output '[అర్థం కాని శబ్దం]'.
8. Keep spoken length proportionate to the segment duration.

COMMON CREATOR PHONETIC PATTERNS IN TELUGU REELS:
- 'shoot chesetappudu' phonetically resembles ASR tokens like 'suddhaes toppers', 'chaslo topo'
- 'use chesina techniques entante' phonetically resembles 'use tells tecnic sendente', 'accessories from techniques'
- 'arrange chesamo daanne' phonetically resembles 'r&jaster namo dannaye', 'aran chaisar na mo'
- 'cinematic ga ravali ante' phonetically resembles 'sinimatic garavalante', 'cinematic gar bewalande'

RETURN FORMAT:
Return ONLY a valid JSON object matching this schema:
{
  "segments": [
    {
      "id": "segment-id",
      "text": "తెలుగు వాక్యం..."
    }
  ]
}
"""


def validate_restoration_output(
    original_segments: List[TranscriptSegment],
    parsed_json: Dict[str, Any],
) -> List[Dict[str, str]]:
    """
    Strict validation of Gemini restoration output.
    Enforces:
    - JSON structure contains 'segments' list
    - Segment count matches original input exactly
    - Every original segment ID exists exactly once
    - Ordering matches original segment ordering
    - No timestamps or time properties were generated or returned
    - Non-empty text per segment
    - Reasonable text-length guardrail based on segment duration
    """
    if not isinstance(parsed_json, dict):
        raise SpeechRestorationValidationError("Root JSON is not an object.")

    returned_segments = parsed_json.get("segments")
    if not isinstance(returned_segments, list):
        raise SpeechRestorationValidationError("'segments' key is missing or not a list.")

    if len(returned_segments) != len(original_segments):
        raise SpeechRestorationValidationError(
            f"Segment count mismatch: expected {len(original_segments)}, got {len(returned_segments)}."
        )

    expected_ids = [s.id for s in original_segments]
    seen_ids = set()

    for idx, (orig, ret) in enumerate(zip(original_segments, returned_segments)):
        if not isinstance(ret, dict):
            raise SpeechRestorationValidationError(f"Segment item at index {idx} is not an object.")

        ret_id = ret.get("id")
        if not ret_id:
            raise SpeechRestorationValidationError(f"Segment item at index {idx} is missing 'id'.")

        if ret_id in seen_ids:
            raise SpeechRestorationValidationError(f"Duplicate segment ID '{ret_id}' found in output.")
        seen_ids.add(ret_id)

        if ret_id != orig.id:
            raise SpeechRestorationValidationError(
                f"Segment order or ID mismatch at index {idx}: expected '{orig.id}', got '{ret_id}'."
            )

        # Reject any timestamps returned by Gemini
        forbidden_time_keys = {"start_time", "end_time", "start", "end", "timestamp", "timestamps"}
        present_forbidden = forbidden_time_keys.intersection(ret.keys())
        if present_forbidden:
            raise SpeechRestorationValidationError(
                f"Gemini returned forbidden timestamp keys: {present_forbidden} in segment '{ret_id}'."
            )

        text = ret.get("text")
        if text is None or not str(text).strip():
            raise SpeechRestorationValidationError(f"Segment '{ret_id}' returned empty text.")

        # Text-length guardrail: maximum ~35 characters per second of audio duration (with a floor of 120 chars)
        seg_duration = max(float(orig.end_time - orig.start_time), 0.5)
        max_allowed_chars = max(120, int(seg_duration * 35))
        if len(str(text)) > max_allowed_chars:
            raise SpeechRestorationValidationError(
                f"Segment '{ret_id}' text length ({len(str(text))} chars) exceeds duration guardrail ({max_allowed_chars} chars)."
            )

    if set(expected_ids) != seen_ids:
        missing = set(expected_ids) - seen_ids
        raise SpeechRestorationValidationError(f"Missing segment IDs in output: {missing}.")

    return returned_segments


class GeminiSpeechRestorationProvider(BaseSpeechRestorationProvider):
    """
    Production-grade Telugu speech restoration powered by Google Gemini LLM.
    Uses structured batch JSON inference and enforces strict 1:1 segment preservation.
    Falls back gracefully to raw Whisper transcription on timeout, quota, or validation error.
    """

    def __init__(
        self,
        api_key: str,
        model: Optional[str] = None,
        timeout: float = 30.0,
    ):
        self.api_key = api_key.strip() if api_key else ""
        self.model = model or getattr(settings, "GEMINI_MODEL", "gemini-3.5-flash-lite")
        self.timeout = timeout
        self.provider_name = "gemini_speech_restoration"

    async def restore_telugu_speech(
        self,
        segments: List[TranscriptSegment],
        context: Optional[str] = None,
    ) -> SpeechRestorationResult:
        """
        Restore phonetically noisy Telugu segments via Gemini REST API.
        Guarantees start_time and end_time remain 100% authoritative from Whisper.
        """
        if not segments:
            return SpeechRestorationResult(
                segments=[],
                full_text="",
                is_restored=False,
                provider_name=self.provider_name,
                notice=None,
                metadata={"empty_input": True},
            )

        if not self.api_key:
            logger.info("Gemini API key is not configured; bypassing Telugu speech restoration.")
            return SpeechRestorationResult(
                segments=segments,
                full_text="\n\n".join(s.text for s in segments),
                is_restored=False,
                provider_name="local_whisper",
                notice="Telugu restoration unavailable; using local transcription.",
                metadata={"reason": "api_key_missing"},
            )

        # Prepare payload for Gemini
        segments_payload = [
            {
                "id": s.id,
                "duration": round(float(s.end_time - s.start_time), 2),
                "text": s.text.strip(),
            }
            for s in segments
        ]

        user_content = (
            f"Context: {context or 'Cinematography and video creation short-form content.'}\n\n"
            f"Here are the raw Whisper transcript segments:\n"
            f"{json.dumps(segments_payload, ensure_ascii=False, indent=2)}\n\n"
            f"Restore each segment into clean, grammatically natural Telugu Unicode script following all system rules. "
            f"Return ONLY valid JSON."
        )

        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent?key={self.api_key}"

        request_body = {
            "system_instruction": {"parts": [{"text": SYSTEM_RESTORATION_PROMPT}]},
            "contents": [{"parts": [{"text": user_content}]}],
            "generationConfig": {
                "temperature": 0.2,
                "responseMimeType": "application/json",
            },
        }

        max_attempts = 2
        for attempt in range(max_attempts):
            try:
                async with httpx.AsyncClient(timeout=self.timeout) as client:
                    response = await client.post(url, json=request_body)

                if response.status_code == 503 and attempt < max_attempts - 1:
                    logger.info("Gemini 503 transient error, retrying in 1.5s...")
                    await asyncio.sleep(1.5)
                    continue

                if response.status_code != 200:
                    logger.warning(
                        "Gemini speech restoration HTTP error (status %d). Falling back to local Whisper transcript.",
                        response.status_code,
                    )
                    return self._fallback_result(
                        segments=segments,
                        reason=f"http_error_{response.status_code}",
                    )

                data = response.json()
                raw_text = data["candidates"][0]["content"]["parts"][0]["text"]
                parsed_json = json.loads(raw_text)

                # Strict 1:1 validation
                validated_items = validate_restoration_output(segments, parsed_json)

                # Build restored segments while strictly preserving original timestamps
                restored_segments: List[TranscriptSegment] = []
                for orig, item in zip(segments, validated_items):
                    restored_text = str(item["text"]).strip()
                    restored_segments.append(
                        TranscriptSegment(
                            id=orig.id,
                            text=restored_text,
                            start_time=orig.start_time,  # 100% authoritative Whisper start
                            end_time=orig.end_time,      # 100% authoritative Whisper end
                            words=[],                    # Word timestamps not fabricated
                            speaker=orig.speaker,
                            confidence=0.95,
                        )
                    )

                full_text = "\n\n".join(s.text for s in restored_segments)
                return SpeechRestorationResult(
                    segments=restored_segments,
                    full_text=full_text,
                    is_restored=True,
                    provider_name=self.provider_name,
                    notice=None,
                    metadata={
                        "model": self.model,
                        "restored_count": len(restored_segments),
                        "speech_restoration_applied": True,
                    },
                )

            except SpeechRestorationValidationError as e:
                logger.warning(
                    "Gemini Telugu speech restoration contract validation failed: %s. Falling back to local Whisper transcript.",
                    str(e),
                )
                return self._fallback_result(segments=segments, reason="contract_validation_failed")
            except (httpx.RemoteProtocolError, httpx.ConnectError, httpx.TimeoutException) as e:
                if attempt < max_attempts - 1:
                    logger.info("Gemini transient network error (%s), retrying in 1.5s...", type(e).__name__)
                    await asyncio.sleep(1.5)
                    continue
                logger.warning("Gemini speech restoration network error (%s). Falling back.", type(e).__name__)
                reason = "timeout" if isinstance(e, httpx.TimeoutException) else f"network_{type(e).__name__}"
                return self._fallback_result(segments=segments, reason=reason)
            except Exception as e:
                logger.warning(
                    "Gemini Telugu speech restoration error (%s). Falling back to local Whisper transcript.",
                    type(e).__name__,
                )
                return self._fallback_result(segments=segments, reason=f"error_{type(e).__name__}")

    def _fallback_result(self, segments: List[TranscriptSegment], reason: str) -> SpeechRestorationResult:
        """Safe fallback returning original Whisper segments without modifying timestamps."""
        return SpeechRestorationResult(
            segments=segments,
            full_text="\n\n".join(s.text for s in segments),
            is_restored=False,
            provider_name="local_whisper",
            notice="Telugu restoration unavailable; using local transcription.",
            metadata={
                "fallback_reason": reason,
                "speech_restoration_applied": False,
            },
        )


class DisabledSpeechRestorationProvider(BaseSpeechRestorationProvider):
    """No-op provider returned when feature flag is disabled or key is unset."""

    async def restore_telugu_speech(
        self,
        segments: List[TranscriptSegment],
        context: Optional[str] = None,
    ) -> SpeechRestorationResult:
        return SpeechRestorationResult(
            segments=segments,
            full_text="\n\n".join(s.text for s in segments),
            is_restored=False,
            provider_name="local_whisper",
            notice=None,
            metadata={"speech_restoration_disabled": True},
        )


def get_speech_restoration_provider(enabled: Optional[bool] = None) -> BaseSpeechRestorationProvider:
    """
    Factory resolving active speech restoration provider.
    Honors ENABLE_HYBRID_SPEECH_RESTORATION feature flag and GEMINI_API_KEY presence.
    """
    is_enabled = enabled if enabled is not None else getattr(settings, "ENABLE_HYBRID_SPEECH_RESTORATION", True)
    if not is_enabled:
        return DisabledSpeechRestorationProvider()

    api_key = settings.GEMINI_API_KEY
    if not api_key or not api_key.strip():
        return DisabledSpeechRestorationProvider()

    model = getattr(settings, "GEMINI_MODEL", "gemini-3.5-flash-lite")
    return GeminiSpeechRestorationProvider(api_key=api_key, model=model)
